function doDicionario(dic, valor, idioma, genero) {
  const item = dic[chave(valor)];
  if (!item) return null;
  const t = item[idioma];
  return typeof t === 'object' ? t[genero === 'masculino' ? 'm' : 'f'] : t;
}

// Troca termos de categoria dentro de um texto livre (ex.: "Sub-17 e futsal", "2024 – atual")
function termosComuns(texto, idioma) {
  if (idioma === 'pt' || !texto) return texto;
  const en = idioma === 'en';
  return texto
    .replace(/\bSub-?(\d{2})\b/gi, (_, n) => (en ? `U-${n}` : `Sub-${n}`))
    .replace(/\bprofissional\b/gi, en ? 'Professional' : 'Profesional')
    .replace(/\b(atual|hoje)\b/gi, en ? 'present' : 'actualidad')
    .replace(/\btemporada (\d{4})\b/gi, (_, a) => (en ? `${a} season` : `Temporada ${a}`))
    .replace(/\bjuvenil\b/gi, en ? 'Youth' : 'Juvenil')
    .replace(/\bUruguai\b/g, 'Uruguay')
    .replace(/\bParaguai\b/g, 'Paraguay')
    .replace(/\bEquador\b/g, 'Ecuador')
    .replace(/ e /g, en ? ' and ' : ' y ');
}

